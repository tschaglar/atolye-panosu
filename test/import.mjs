import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const file = process.argv[2];
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto('http://127.0.0.1:8765/index.html');
await page.evaluate(() => { localStorage.clear(); });
await page.reload(); await page.waitForSelector('form[data-form="login"]');
await page.fill('#li-user', 'caglar'); await page.fill('#li-pass', '123456'); await page.click('form[data-form="login"] button[type=submit]');
await page.waitForSelector('#tabs:not([hidden])');
await page.click('#meChip'); await page.setInputFiles('#imp-file', file);
await page.waitForSelector('text=Bazı kişilerin hesabı yok');
console.log('uyarı:', (await page.textContent('.sheet .lead')).trim().slice(0, 120));
await page.click('[data-act="importAnyway"]');
await page.waitForSelector('.toast:has-text("Aktarıldı")', { timeout: 10000 });
console.log('sonuç:', await page.textContent('.toast:has-text("Aktarıldı")'));
const db = await page.evaluate(() => ({ firms: [...window.__fakeDb.firms.values()].map(f => f.name), jobs: [...window.__fakeDb.jobs.values()].map(j => [j.title, j.status, j.price, j.plate]), company: window.__fakeDb.settings.get('company') }));
console.log(JSON.stringify(db));
console.log(errs.length ? 'HATA ' + errs.join(' | ') : 'hata yok');
await browser.close();
